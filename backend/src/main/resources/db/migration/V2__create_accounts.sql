-- A financial account a user tracks: a bank account, a credit card, cash, ...
--
-- Accounts hold financial history, so they are archived rather than deleted
-- once they have transactions (see AccountService.archive).
CREATE TABLE accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(80)  NOT NULL,
    type       VARCHAR(20)  NOT NULL,
    currency   VARCHAR(3)   NOT NULL,
    archived   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_accounts_type CHECK (type IN ('CHECKING', 'SAVINGS', 'CREDIT_CARD', 'CASH', 'INVESTMENT', 'OTHER')),
    CONSTRAINT ck_accounts_currency CHECK (currency ~ '^[A-Z]{3}$')
);

-- Every account query is scoped by user_id, so it leads every index.
CREATE INDEX idx_accounts_user_id ON accounts (user_id);

-- One user cannot have two accounts whose names differ only by case.
CREATE UNIQUE INDEX uq_accounts_user_name ON accounts (user_id, lower(name));
