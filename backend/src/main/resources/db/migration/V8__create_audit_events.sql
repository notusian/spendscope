-- Security relevant events, surfaced to the user on the Security page.
--
-- user_id is nullable on purpose: a failed login for an unknown email has no
-- user to attribute it to.
--
-- metadata NEVER contains passwords, password hashes, session identifiers,
-- CSRF tokens or raw authentication headers. See AuditService.
CREATE TABLE audit_events (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      REFERENCES users (id) ON DELETE CASCADE,
    event_type  VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata    JSONB       NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX idx_audit_events_user_occurred_at ON audit_events (user_id, occurred_at DESC);
