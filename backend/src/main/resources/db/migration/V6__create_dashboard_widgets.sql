-- One configurable card on a user's dashboard.
--
-- The strongly typed knobs every widget has (metric, period, chart type) are
-- real columns so the database can validate them. "configuration" is JSONB for
-- the handful of widget-specific extras (result limits, category filters) that
-- would otherwise need a column per widget type.
CREATE TABLE dashboard_widgets (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    metric_type       VARCHAR(40) NOT NULL,
    group_by          VARCHAR(20),
    period            VARCHAR(20) NOT NULL,
    comparison_period VARCHAR(20),
    chart_type        VARCHAR(20) NOT NULL,
    position          INTEGER     NOT NULL,
    size              VARCHAR(10) NOT NULL,
    configuration     JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_widgets_position_non_negative CHECK (position >= 0),
    CONSTRAINT ck_widgets_size CHECK (size IN ('SMALL', 'MEDIUM', 'LARGE', 'FULL'))
);

-- Widgets are always fetched as "the whole dashboard, in order".
CREATE INDEX idx_widgets_user_position ON dashboard_widgets (user_id, position);
