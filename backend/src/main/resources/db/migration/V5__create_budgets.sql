-- A monthly spending limit for one category.
--
-- Only the limit is stored. Amount spent is always derived from transactions
-- so the two can never drift apart.
CREATE TABLE budgets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id BIGINT         NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    month       DATE           NOT NULL,
    amount      NUMERIC(19, 4) NOT NULL,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- "month" is the first day of the budgeted month, e.g. 2026-09-01.
    CONSTRAINT ck_budgets_month_is_first_day CHECK (EXTRACT(DAY FROM month) = 1),
    CONSTRAINT ck_budgets_amount_positive CHECK (amount > 0),
    CONSTRAINT uq_budgets_user_category_month UNIQUE (user_id, category_id, month)
);

CREATE INDEX idx_budgets_user_month ON budgets (user_id, month);
