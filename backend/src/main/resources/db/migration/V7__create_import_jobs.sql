-- Audit record of one CSV upload.
--
-- The uploaded file itself is never persisted (see docs/decisions.md); only
-- these counters survive so the user can see what an import did.
CREATE TABLE import_jobs (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    account_id          BIGINT      NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    original_filename   VARCHAR(255) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    rows_processed      INTEGER     NOT NULL DEFAULT 0,
    rows_imported       INTEGER     NOT NULL DEFAULT 0,
    rows_rejected       INTEGER     NOT NULL DEFAULT 0,
    duplicates_detected INTEGER     NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at        TIMESTAMPTZ,
    CONSTRAINT ck_import_jobs_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED'))
);

CREATE INDEX idx_import_jobs_user_created_at ON import_jobs (user_id, created_at DESC);
