-- Users of SpendScope. One row per registered person.
--
-- Emails are stored already normalised to lower case by the application
-- (see UserService.normaliseEmail) so a plain UNIQUE constraint is enough to
-- make "Alice@Example.com" and "alice@example.com" the same account.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    is_demo       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- Demo accounts are disposable; this index supports the cleanup query.
CREATE INDEX idx_users_demo_created_at ON users (created_at) WHERE is_demo;
