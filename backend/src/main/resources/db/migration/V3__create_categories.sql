-- Spending/income categories.
--
-- user_id IS NULL  -> built-in category, readable by every user, editable by none.
-- user_id IS NOT NULL -> custom category owned by exactly one user.
CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(60) NOT NULL,
    type       VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_categories_type CHECK (type IN ('EXPENSE', 'INCOME'))
);

-- Two partial unique indexes: built-in names are globally unique, custom names
-- are unique per owner. A single UNIQUE(user_id, name) would not work because
-- NULL never equals NULL in SQL, so built-ins would not be de-duplicated.
CREATE UNIQUE INDEX uq_categories_builtin_name ON categories (lower(name)) WHERE user_id IS NULL;
CREATE UNIQUE INDEX uq_categories_user_name ON categories (user_id, lower(name)) WHERE user_id IS NOT NULL;

CREATE INDEX idx_categories_user_id ON categories (user_id);

