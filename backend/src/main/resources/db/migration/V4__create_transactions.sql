-- Individual money movements.
--
-- SIGN CONVENTION: amount is signed. Negative = money leaving the account
-- (spending), positive = money arriving (salary, refund). Analytics reports
-- "spending" as the absolute value of the negative amounts.
--
-- NUMERIC(19, 4) - never float/double. Binary floating point cannot represent
-- 0.10 exactly, and rounding drift is unacceptable for money.
CREATE TABLE transactions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    account_id             BIGINT         NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    category_id            BIGINT         REFERENCES categories (id) ON DELETE SET NULL,
    date                   DATE           NOT NULL,
    description            VARCHAR(500)   NOT NULL,
    normalized_description VARCHAR(500)   NOT NULL,
    merchant               VARCHAR(120),
    amount                 NUMERIC(19, 4) NOT NULL,
    currency               VARCHAR(3)     NOT NULL,
    fingerprint            VARCHAR(64)    NOT NULL,
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_transactions_amount_nonzero CHECK (amount <> 0),
    CONSTRAINT ck_transactions_currency CHECK (currency ~ '^[A-Z]{3}$')
);

-- Indexes mirror the real access patterns; every one is user-scoped first
-- because no query ever crosses users.
CREATE INDEX idx_transactions_user_date ON transactions (user_id, date DESC);
CREATE INDEX idx_transactions_user_category_date ON transactions (user_id, category_id, date DESC);
CREATE INDEX idx_transactions_user_account_date ON transactions (user_id, account_id, date DESC);

-- Duplicate detection lookup. Deliberately NOT unique: a user can legitimately
-- buy the same coffee twice on the same day. Duplicates are reported, never
-- silently blocked or overwritten.
CREATE INDEX idx_transactions_user_fingerprint ON transactions (user_id, fingerprint);

-- Supports "top merchants" aggregation.
CREATE INDEX idx_transactions_user_merchant ON transactions (user_id, merchant);
