import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
await page.goto('http://localhost:5173/')
await page.getByRole('button', { name: 'Try the demo' }).click()
await page.waitForURL(/dashboard/, { timeout: 30000 })
await page.waitForTimeout(2500)
await page.screenshot({ path: '/tmp/ss-dashboard.png', fullPage: true })
await page.getByRole('link', { name: 'Transactions' }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: '/tmp/ss-transactions.png' })
await page.getByRole('link', { name: 'Budgets' }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: '/tmp/ss-budgets.png' })
// Mobile viewport
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } })
await mobile.goto('http://localhost:5173/')
await mobile.getByRole('button', { name: 'Try the demo' }).click()
await mobile.waitForURL(/dashboard/, { timeout: 30000 })
await mobile.waitForTimeout(2500)
await mobile.screenshot({ path: '/tmp/ss-mobile.png' })
await browser.close()
